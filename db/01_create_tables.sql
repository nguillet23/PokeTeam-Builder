-- PokéTeam Builder: create the five tables (PostgreSQL / Supabase).
-- Matches Designs/er_diagram.svg and Designs/schema.svg.
--
-- Run order:
--   1. 01_create_tables.sql   (this file: drops and recreates everything)
--   2. 02_reference_data.sql  (loads POKEMON, ABILITY, POKEMON_ABILITY from the CSVs)
--
-- This file can be pasted into the Supabase SQL Editor, or run with psql.
-- Unquoted names are folded to lowercase by PostgreSQL (POKEMON -> pokemon).

-- ---------------------------------------------------------------------------
-- Drop any existing tables so this script can be re-run.
-- ---------------------------------------------------------------------------
DROP TABLE IF EXISTS PARTY_MEMBER    CASCADE;
DROP TABLE IF EXISTS TRAINER         CASCADE;
DROP TABLE IF EXISTS POKEMON_ABILITY CASCADE;
DROP TABLE IF EXISTS ABILITY         CASCADE;
DROP TABLE IF EXISTS POKEMON         CASCADE;

-- ---------------------------------------------------------------------------
-- Reference data (loaded from the PokeAPI dataset)
-- ---------------------------------------------------------------------------

-- One row per Pokémon, Gen 1-9. pokemon_id is the PokeAPI id.
-- R1: one or two different types; type2 is NULL for single-type Pokémon.
-- R3: alternate forms are one row; a regional variant is its own row with
--     its own pokemon_id but the same dex_number (so dex_number is NOT unique).
CREATE TABLE POKEMON (
    pokemon_id INTEGER     NOT NULL,
    dex_number INTEGER     NOT NULL,
    name       VARCHAR(50) NOT NULL,
    type1      VARCHAR(10) NOT NULL,
    type2      VARCHAR(10) NULL,
    CONSTRAINT pk_pokemon       PRIMARY KEY (pokemon_id),
    CONSTRAINT uk_pokemon_name  UNIQUE (name),
    CONSTRAINT ck_pokemon_type1 CHECK (type1 IN (
        'normal', 'fire', 'water', 'electric', 'grass', 'ice',
        'fighting', 'poison', 'ground', 'flying', 'psychic', 'bug',
        'rock', 'ghost', 'dragon', 'dark', 'steel', 'fairy')),
    CONSTRAINT ck_pokemon_type2 CHECK (type2 IN (
        'normal', 'fire', 'water', 'electric', 'grass', 'ice',
        'fighting', 'poison', 'ground', 'flying', 'psychic', 'bug',
        'rock', 'ghost', 'dragon', 'dark', 'steel', 'fairy')),  -- NULL passes
    CONSTRAINT ck_pokemon_types CHECK (type1 <> type2)          -- NULL type2 passes
);

-- One row per ability. ability_id is the PokeAPI ability id.
CREATE TABLE ABILITY (
    ability_id INTEGER     NOT NULL,
    name       VARCHAR(50) NOT NULL,
    CONSTRAINT pk_ability      PRIMARY KEY (ability_id),
    CONSTRAINT uk_ability_name UNIQUE (name)
);

-- R2: Pokémon M:N Ability. Each row is one legal (Pokémon, ability) pair.
-- ability_slot 1-3 (3 = hidden) + UNIQUE (pokemon_id, ability_slot)
-- => at most three abilities per Pokémon.
-- R8: FKs use the default (NO ACTION), so referenced rows can't be deleted.
CREATE TABLE POKEMON_ABILITY (
    pokemon_id   INTEGER  NOT NULL,
    ability_id   INTEGER  NOT NULL,
    ability_slot SMALLINT NOT NULL,
    CONSTRAINT pk_pokemon_ability PRIMARY KEY (pokemon_id, ability_id),
    CONSTRAINT uk_pa_pokemon_slot UNIQUE (pokemon_id, ability_slot),
    CONSTRAINT ck_pa_slot         CHECK (ability_slot BETWEEN 1 AND 3),
    CONSTRAINT fk_pa_pokemon FOREIGN KEY (pokemon_id)
        REFERENCES POKEMON (pokemon_id),
    CONSTRAINT fk_pa_ability FOREIGN KEY (ability_id)
        REFERENCES ABILITY (ability_id)
);

-- ---------------------------------------------------------------------------
-- User data (trainers and their team)
-- ---------------------------------------------------------------------------

-- R4: each trainer has exactly one team (their PARTY_MEMBER rows).
CREATE TABLE TRAINER (
    trainer_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    name       VARCHAR(50) NOT NULL,
    CONSTRAINT pk_trainer      PRIMARY KEY (trainer_id),
    CONSTRAINT uk_trainer_name UNIQUE (name)
);

-- R5: at most 6 per team (slot 1-6, one Pokémon per slot).
-- R6: no repeated Pokémon on a team.
-- R7: the composite FK to POKEMON_ABILITY makes sure the Pokémon exists
--     AND the chosen ability is one of its real abilities.
-- R8: deleting a trainer deletes their party members; reference rows in use
--     can't be deleted.
CREATE TABLE PARTY_MEMBER (
    party_member_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    trainer_id      INTEGER  NOT NULL,
    party_slot      SMALLINT NOT NULL,
    pokemon_id      INTEGER  NOT NULL,
    ability_id      INTEGER  NOT NULL,
    CONSTRAINT pk_party_member       PRIMARY KEY (party_member_id),
    CONSTRAINT uk_pm_trainer_slot    UNIQUE (trainer_id, party_slot),
    CONSTRAINT uk_pm_trainer_pokemon UNIQUE (trainer_id, pokemon_id),
    CONSTRAINT ck_pm_slot            CHECK (party_slot BETWEEN 1 AND 6),
    CONSTRAINT fk_pm_trainer FOREIGN KEY (trainer_id)
        REFERENCES TRAINER (trainer_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_pm_pokemon_ability FOREIGN KEY (pokemon_id, ability_id)
        REFERENCES POKEMON_ABILITY (pokemon_id, ability_id)
);
